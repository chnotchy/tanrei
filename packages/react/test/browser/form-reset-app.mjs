const countries = () => [h(Option, { key: 'ca', value: 'ca' }, 'Canada'), h(Option, { key: 'fr', value: 'fr' }, 'France'), h(Option, { key: 'jp', value: 'jp' }, 'Japan')];
const cities = () => [h(Option, { key: 'tokyo', value: 'tokyo' }, 'Tokyo'), h(Option, { key: 'osaka', value: 'osaka' }, 'Osaka'), h(Option, { key: 'kyoto', value: 'kyoto' }, 'Kyoto')];
const letters = () => ['a', 'b', 'c'].map((value) => h(Checkbox, { key: value, value, label: value.toUpperCase() }));
const radios = () => ['a', 'b', 'c'].map((value) => h(RadioButton, { key: value, value, label: value.toUpperCase() }));

export function App() {
  const [state, setState] = useState(0);
  const s = STATES[state];
  return h(
    'main',
    null,
    h(
      'form',
      { id: 'form' },
      h(Checkbox, { id: 'checkbox', name: 'checkbox', label: 'Checkbox', checked: s.checkbox }),
      h(Switch, { id: 'switch', name: 'switch', label: 'Switch', checked: s.switch }),
      h(RadioButton, { id: 'radio', name: 'radio', value: 'r', label: 'Radio', checked: s.radio }),
      h(RadioGroup, { id: 'radioGroup', name: 'radioGroup', label: 'Radio group', value: s.radioGroup }, radios()),
      h(CheckboxGroup, { id: 'checkboxGroup', name: 'checkboxGroup', label: 'Checkbox group', value: s.checkboxGroup }, letters()),
      h(TextInput, { id: 'text', name: 'text', label: 'Text', value: s.text }),
      h(TextField, { id: 'textField', name: 'textField', label: 'Text field', value: s.textField }),
      h(EmbeddedTextInput, { id: 'embedded', name: 'embedded', label: 'Embedded', value: s.embedded }),
      h(NumberInput, { id: 'number', name: 'number', label: 'Number', value: s.number }),
      h(NumberField, { id: 'numberField', name: 'numberField', label: 'Number field', value: s.numberField }),
      h(ColorInput, { id: 'color', name: 'color', label: 'Color', value: s.color }),
      h(ColorField, { id: 'colorField', name: 'colorField', label: 'Color field', value: s.colorField }),
      h(OneTimeCodeInput, { id: 'code', name: 'code', label: 'Code', length: 4, value: s.code }),
      h(OneTimeCodeField, { id: 'codeField', name: 'codeField', label: 'Code field', length: 4, value: s.codeField }),
      h(Search, { id: 'search', name: 'search', label: 'Search', value: s.search }),
      h(Select, { id: 'select', name: 'select', label: 'Select', value: s.select }, countries()),
      h(SelectField, { id: 'selectField', name: 'selectField', label: 'Select field', value: s.selectField }, countries()),
      h(Combobox, { id: 'combobox', name: 'combobox', label: 'Combobox', value: s.combobox }, cities()),
      h(ComboboxField, { id: 'comboboxField', name: 'comboboxField', label: 'Combobox field', value: s.comboboxField }, cities()),
      h(Combobox, { id: 'comboboxValues', name: 'comboboxValues', label: 'Cities', selection: 'multiple', values: s.comboboxValues }, cities()),
      h(Slider, { id: 'slider', name: 'slider', label: 'Slider', value: s.slider }),
      h(Slider, { id: 'range', name: 'range', label: 'Range', startLabel: 'From', range: true, startValue: s.range[0], value: s.range[1] }),
      h(SliderField, { id: 'sliderField', name: 'sliderField', label: 'Slider field', value: s.sliderField }),
      h(Rating, { id: 'rating', name: 'rating', label: 'Rating', value: s.rating }),
      h(ChipField, { id: 'chips', name: 'chips', label: 'Chips', value: s.chips }),
    ),
    h(Button, { id: 'next', onClick: () => setState(1) }, 'Next'),
  );
}

