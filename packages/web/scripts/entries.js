// The entries of the package beyond its main one, worked out from the shipped systems' components manifests
// (tokens/generated/<id>/components.json) and the component catalog (packages/tokens-build/generated/component-catalog.json).
// The build writes them (scripts/build.js):
//
//   dist/systems/<id>.js, .d.ts      `@tanrei/web/systems/<id>.js`: what system <id> ships — everything the main entry
//                                    registers, and the components the system ships that the default system does not
//   dist/all.js, .d.ts               `@tanrei/web/all`: every component of the package
//   dist/custom-elements/<id>.json   `@tanrei/web/custom-elements/<id>.json`: custom-elements.json without the modules
//                                    of the components system <id> does not ship
//
// `@tanrei/web` itself (src/index.ts) registers the default system's components and no other, in the order its
// frames need; test/entries.test.mjs holds it, and each entry here, to the manifests.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const WEB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REPO = path.resolve(WEB, '../..');
const readJson = (file) => JSON.parse(fs.readFileSync(file, 'utf8'));
const PACKAGE = readJson(path.join(WEB, 'package.json')).name;
/** The default system: the one named like the namespace (tanrei.config.json), whose components the main entry registers. */
export const DEFAULT_SYSTEM = readJson(path.join(REPO, 'tanrei.config.json')).namespace;

/** The directory under src/components/ of an element's own module (`@tanrei/web/components/<dir>`). */
function moduleDir(specifier) {
  const prefix = `${PACKAGE}/components/`;
  if (!specifier?.startsWith(prefix)) throw new Error(`entries: ${specifier} is not a module of ${PACKAGE}/components/*`);
  return specifier.slice(prefix.length);
}

/** The element directories a manifest's components are in, in its order: its classes (stylesheets) have none. */
const elementDirs = (components) => [...new Set(components.filter((component) => component.web?.tag).map((component) => moduleDir(component.web.module)))];

/** The shipped systems' manifests (id → manifest) and the catalog, from the repository. */
export function readManifests(repo = REPO) {
  const generated = path.join(repo, 'tokens/generated');
  const manifests = new Map(
    fs
      .readdirSync(generated, { withFileTypes: true })
      .filter((entry) => entry.isDirectory() && fs.existsSync(path.join(generated, entry.name, 'components.json')))
      .map(({ name }) => [name, readJson(path.join(generated, name, 'components.json'))]),
  );
  return { manifests, catalog: readJson(path.join(repo, 'packages/tokens-build/generated/component-catalog.json')) };
}

/**
 * What each entry registers beyond the main one: system id → the element directories it adds, and `all` → those
 * every component of the package adds. A system that leaves out a component the main entry registers cannot have an
 * entry made of the main one and more: that stops the build rather than write an entry that registers what the
 * system does not ship.
 */
export function entrySets({ manifests, catalog }) {
  const main = manifests.get(DEFAULT_SYSTEM);
  if (!main) throw new Error(`entries: the default system "${DEFAULT_SYSTEM}" has no components manifest`);
  const registered = new Set(elementDirs(main.components));
  const systems = new Map();
  for (const [id, manifest] of manifests) {
    const dirs = elementDirs(manifest.components);
    const missing = [...registered].filter((dir) => !dirs.includes(dir));
    if (missing.length) throw new Error(`entries: "${id}" does not ship ${missing.join(', ')}, which ${PACKAGE} registers — its entry cannot be ${PACKAGE} and more`);
    systems.set(id, dirs.filter((dir) => !registered.has(dir)));
  }
  const all = elementDirs(catalog.components).filter((dir) => !registered.has(dir));
  return { registered, systems, all };
}

/** An entry's module (and its declarations, the same lines): the main entry, then each module it adds. */
const entryText = (from, dirs, note) => [`// GENERATED by packages/web/scripts/build.js — do not edit. ${note}`, `export * from '${from}index.js';`, ...dirs.map((dir) => `export * from '${from}components/${dir}/${dir}.js';`), ''].join('\n');

/** The files the entries are: path under dist/ → text. */
export function entryFiles(read = readManifests()) {
  const { systems, all } = entrySets(read);
  const files = {};
  for (const [id, dirs] of systems) {
    const text = entryText('../', dirs, `The components the "${id}" system ships (tokens/generated/${id}/components.json): those of ${PACKAGE}, and the system's own.`);
    files[`systems/${id}.js`] = text;
    files[`systems/${id}.d.ts`] = text;
  }
  const text = entryText('./', all, 'Every component of the package: those of the default system, and those only other systems ship.');
  files['all.js'] = text;
  files['all.d.ts'] = text;
  return files;
}

/** The bundle's source: every component of the package, from the sources (`export * from './src/…'`). */
export function bundleSource(read = readManifests()) {
  const { all } = entrySets(read);
  return ["export * from './src/index.ts';", ...all.map((dir) => `export * from './src/components/${dir}/${dir}.ts';`), ''].join('\n');
}

/**
 * custom-elements.json for one system: without the modules of the components it does not ship (each component's
 * directory under src/components/, its styles with it), and otherwise the same.
 */
export function systemElements(elements, manifest, catalog) {
  const ships = new Set(elementDirs(manifest.components));
  const gone = new Set(elementDirs(catalog.components).filter((dir) => !ships.has(dir)));
  const dirOf = (modulePath) => /^src\/components\/([^/]+)\//.exec(modulePath)?.[1];
  return { ...elements, modules: elements.modules.filter((module) => !gone.has(dirOf(module.path))) };
}
