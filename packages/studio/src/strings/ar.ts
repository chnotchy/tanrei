//
// Modern Standard Arabic, as the Arabic docs write it (apps/docs/i18n/glossary.md): a command is the verbal noun
// without the article (حفظ، إضافة، إزالة), an instruction to the person is the imperative, Western digits, « » for a
// quoted label and straight quotes for a key of the file ("tokens"), no dash between clauses — and the docs' words
// for the same things: الطبقة، الأساس، قرص الضبط، لوحة الألوان، لون بذرة، صبغة وتشبّع، درجة لونية مثبَّتة، التثبيت مع سبب،
// إعادة التوجيه، قواعد الأنماط، المسوِّغ، الحشو، البناء. Token ids, keys of the layer file, state names and commands
// stay Latin.
//
// Right to left: a string opens with an Arabic word, and a Latin id is not left with punctuation of its own at its
// end (`tanrei.*`, `"{id}.comp.…"`) — it is named by its kind instead (النطاق tanrei). A range is «من 0 إلى 360». The
// only direction mark is the `\u200E` before `#0f766e` in `words.invalidColor` (as the docs write it,
// `&lrm;#0f766e`): that string is given to a component as plain text. Everywhere else a Latin value that the Studio
// puts into a sentence stands in an element of its own that isolates it (`$1`, `$2` in `rules.help`, a family in
// `fonts.missing`), so a sentence needs no mark for it.
