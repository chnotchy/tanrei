// The brand marks (design/brand/): an export from Figma made into the repository's source, the refusals that keep a
// mark one flat color painted by a token, and what `pnpm generate` derives from the shipped marks.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { after, test } from 'node:test';
import { leavesNothingBehind, tempDir } from '../../tools/src/test-tmp.js';
import { MARKS, adaptiveMark, brandFiles, normalizeMark, paintMark } from '../src/emit/brand.js';
import { REPO_ROOT } from '../src/model.js';

leavesNothingBehind(after);

// What Figma's editor exports for a component: the canvas behind the frame, the layer's group and ids.
const EXPORT = `<svg width="512" height="512" viewBox="0 0 512 512" fill="none" xmlns="http://www.w3.org/2000/svg">
<rect width="512" height="512" fill="#F5F5F5"/>
<g id="Logo / Symbol">
<path id="symbol" d="M0 0H10V10Z" fill="black"/>
</g>
</svg>
`;

test('an export becomes the source: its frame, its paths in currentColor, nothing of the editor', () => {
  const source = normalizeMark(EXPORT, { source: 'Figma file F, node 1:2' });
  assert.equal(
    source,
    '<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512" fill="none">\n<!-- Pulled from Figma file F, node 1:2 by `pnpm brand:pull`. Change the mark in Figma, not here. -->\n<path d="M0 0H10V10Z" fill="currentColor"/>\n</svg>\n',
  );
  assert.equal(normalizeMark(source, { source: 'Figma file F, node 1:2' }), source, 'a source is its own normal form');
});

test('a mark that is not flat shapes in one color is refused, with what was found', () => {
  const swap = (from, to) => EXPORT.replace(from, to);
  assert.throws(() => normalizeMark(swap('<path id="symbol"', '<path d="M1 1Z" fill="#ff0000"/><path id="symbol"')), /2 colors/);
  assert.throws(() => normalizeMark(swap('fill="black"', 'fill="black" stroke="red"')), /stroke/);
  assert.throws(() => normalizeMark(swap('fill="black"', 'fill="url(#g)"')), /gradient/);
  assert.throws(() => normalizeMark(EXPORT.replace('</svg>', '<defs><linearGradient id="g"/></defs></svg>')), /<defs>/);
  assert.throws(() => normalizeMark(swap('<g id="Logo / Symbol">', '<g opacity="0.5">')), /opacity/);
  assert.throws(() => normalizeMark(swap('<path id="symbol" d="M0 0H10V10Z" fill="black"/>', '<text>T</text>')), /<text>/);
  assert.throws(() => normalizeMark(swap('<rect width="512" height="512"', '<rect width="500" height="512"')), /rectangle/);
  assert.throws(() => normalizeMark('<svg width="1" height="1"><path d="M0 0" fill="#000"/></svg>'), /viewBox/);
});

test('a painted copy has the color, the favicon one rule for each scheme and contrast', () => {
  const source = normalizeMark(EXPORT);
  assert.match(paintMark(source, '#1b1b1b'), /<path d="M0 0H10V10Z" fill="#1b1b1b"\/>/);
  const adaptive = adaptiveMark(source, { light: '#111111', dark: '#eeeeee', 'light-high': '#000000', 'dark-high': '#ffffff' });
  assert.match(adaptive, /<style>path \{ fill: #111111 \} @media \(prefers-color-scheme: dark\) \{ path \{ fill: #eeeeee \} \} @media \(prefers-contrast: more\) \{ path \{ fill: #000000 \} \} @media \(prefers-color-scheme: dark\) and \(prefers-contrast: more\) \{ path \{ fill: #ffffff \} \}<\/style>/);
  assert.doesNotMatch(adaptive, /currentColor/, 'an image inherits no color');
});

test('the shipped marks are as the pull writes them, and generate paints them in on-surface', () => {
  const colors = { light: { 'on-surface': { value: { hex: '#1b1b1b' } } }, dark: { 'on-surface': { value: { hex: '#ebebeb' } } } };
  const files = brandFiles(REPO_ROOT, colors);
  for (const mark of MARKS) {
    assert.match(files[`design/brand/generated/${mark}.light.svg`], /fill="#1b1b1b"/);
    assert.match(files[`design/brand/generated/${mark}.dark.svg`], /fill="#ebebeb"/);
    assert.match(files[`design/brand/generated/${mark}.light.svg`], /Generated by `pnpm generate`/);
  }
  assert.ok(files['design/brand/generated/symbol.adaptive.svg']);
});

test('a source edited by hand is refused', () => {
  const root = tempDir('brand');
  fs.mkdirSync(path.join(root, 'design/brand'), { recursive: true });
  fs.writeFileSync(path.join(root, 'design/brand/symbol.svg'), normalizeMark(EXPORT).replace('fill="currentColor"', 'fill="#1b1b1b"'));
  assert.throws(() => brandFiles(root, { light: {}, dark: {} }), /not as `pnpm brand:pull` writes it/);
});
