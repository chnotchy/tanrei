// A design system's components manifest: the one list of what a system ships, for whatever suggests or checks a
// component — a coding assistant, an editor, a lint, the documentation, a platform's entries. A system has a manifest
// at tokens/generated/<id>/components.json (`@tanrei/web/systems/<id>.components.json`), and `tanrei build` writes a
// product's into its `tokens` output.
//
// It is worked out, never written by hand, from two things:
//   - the system's chain of layers — what it leaves out (`componentChoices`) and which components live in a layer it
//     does not descend from (`outsideComponents`), as the stylesheets read them (layers.js);
//   - the component catalog, packages/tokens-build/generated/component-catalog.json: every component with a spec,
//     where it lives, its names on each platform and its `variant` prop — the same for every system
//     (components-catalog.js writes it from the specs and from what the platforms generate from them).
//
// A component's `import` is the module a product imports to have it registered in this system: on the web, the entry
// of the shipped system that ships it — `@tanrei/web` for the default system's components, `@tanrei/web/<id>`
// for another system's — and, for a component no system the product is built on ships (one the product brings back
// or includes from another layer), its own module; in React, the package's one entry. That is decided in one place,
// `importOf`, so that an entry that changes what it registers changes every manifest with it. `module` is the
// component's own module: it registers the component, and the components it is drawn with, in any system.
import fs from 'node:fs';
import path from 'node:path';
import { CONFIG } from './config.js';
import { DEFAULT_SYSTEM, availabilityOf, componentChoices, outsideComponents } from './layers.js';

/** The catalog of every component, relative to the repository (or to the vocabulary the published CLI carries). */
export const CATALOG_FILE = 'packages/tokens-build/generated/component-catalog.json';
/** A shipped system's manifest, relative to the directory that holds tokens/. */
export const manifestFile = (id) => `tokens/generated/${id}/components.json`;

const WEB = `${CONFIG.packages.npmScope}/web`;
const REACT = `${CONFIG.packages.npmScope}/react`;

/**
 * The web package's entry that registers a shipped system's components: `@tanrei/web` the default system's, and
 * `@tanrei/web/<id>` another's (packages/web/scripts/build.js writes those from the systems' manifests).
 */
export const webEntryOf = (system) => (system === DEFAULT_SYSTEM ? WEB : `${WEB}/${system}`);

/**
 * The module of each platform's package that registers `component` (a catalog entry) for a product: the one place an
 * entry's contents are decided.
 * @param {string | null} system the shipped system, nearest the product, that ships the component; null where none
 *   does (a component the product brings back or includes from another layer)
 * @returns {{ web: string, react: string }}
 */
export function importOf(component, system) {
  return {
    web: system ? webEntryOf(system) : component.web?.module,
    react: REACT,
  };
}

/** The note a manifest opens with: what wrote it, and what it holds. */
export const manifestComment = (id, by) =>
  `GENERATED by ${by} — do not edit. The components the "${id}" system ships, each with the module that registers it; the components it does not have, with the layer that left each out and what to use instead, or the layer it lives in; and the variant values it leaves out.`;

/** The catalog under `root` (the repository, or the published CLI's vocabulary), or null where none has been generated. */
export function readComponentCatalog(root) {
  const file = path.join(root, CATALOG_FILE);
  return fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : null;
}

/**
 * The variant values a chain adds to an axis: `vocabulary["<axis>.<value>"]` with `from` (a value on a component
 * axis, the second kind of extension), in the order the layers declare them.
 */
function addedValues(chain, axis) {
  if (!axis) return [];
  const prefix = `${axis}.`;
  return chain.flatMap((layer) =>
    Object.entries(layer.vocabulary ?? {})
      .filter(([id, entry]) => id.startsWith(prefix) && !id.slice(prefix.length).includes('.') && entry && typeof entry === 'object' && 'from' in entry && !('document' in entry))
      .map(([id]) => id.slice(prefix.length)),
  );
}

/**
 * The manifest's `omitted`: the components the system a chain makes does not have, by name — each a component a layer
 * left out (`omittedBy`, with its `reason` and what to use instead, `insteadUse`), or one that lives in a layer the
 * chain does not descend from (`providedBy`). Needs no catalog, so the stylesheets read the same list the manifest
 * gives (`replacementsOf`).
 * @param {object[]} chain layers, root first
 * @param {Map<string, string>} held `heldComponents`
 * @returns {Array<{ name: string, omittedBy?: string, providedBy?: string, reason?: string, insteadUse?: string[] }>}
 */
export function omittedOf(chain, held) {
  const { components: left } = componentChoices(chain);
  return [
    ...[...left].map(([name, { layer, reason, insteadUse }]) => ({ name, omittedBy: layer, ...(reason ? { reason } : {}), ...(insteadUse ? { insteadUse } : {}) })),
    ...Object.entries(outsideComponents(chain, held)).map(([name, layer]) => ({ name, providedBy: layer })),
  ].sort((a, b) => a.name.localeCompare(b.name));
}

/**
 * What a system uses instead of each component it does not have, from its manifest's `omitted` (`omittedOf`):
 * component → the components named in its `insteadUse`, in order. Every entry that names one counts, whatever the
 * reason it is omitted, so a component that lives in another layer is listed as soon as its entry names a replacement.
 * The stylesheets carry it as `--tanrei-unavailable-replacement` (emit/css.js), which an element names in its report.
 * @param {Array<{ name: string, insteadUse?: string[] }>} omitted
 * @returns {Record<string, string[]>}
 */
export function replacementsOf(omitted) {
  return Object.fromEntries(omitted.filter((entry) => entry.insteadUse?.length).map((entry) => [entry.name, [...entry.insteadUse]]));
}

/**
 * What a system's stylesheet says of what the system does not have (emit/css.js `emitCss` options): the components and
 * variant values it leaves out, the components that live in a layer it does not extend, and what it uses instead —
 * the same for a shipped system's sheet and a product's.
 * @param {object[]} chain layers, root first
 * @param {Map<string, string>} held `heldComponents`
 */
export function sheetAvailability(chain, held) {
  return { unavailable: availabilityOf(chain), outside: outsideComponents(chain, held), replacements: replacementsOf(omittedOf(chain, held)) };
}

/** The names of the catalog's components the system a chain makes ships. */
const shipsIn = (chain, catalog, held) => {
  const { components: left } = componentChoices(chain);
  const outside = outsideComponents(chain, held);
  return new Set(catalog.components.map((component) => component.name).filter((name) => !left.has(name) && !outside[name]));
};

/**
 * The manifest of the system a chain makes.
 * @param {object[]} chain layers, root first; the last one is the system
 * @param {{ components: object[] }} catalog the component catalog
 * @param {Map<string, string>} held where each component that lives in a layer lives (`heldComponents`)
 * @param {Iterable<string>} shipped the ids of the shipped systems: each has its own entry on every platform
 */
export function componentsManifest(chain, catalog, held, shipped) {
  if (!shipped) throw new Error('componentsManifest: name the shipped systems, whose entries register their components');
  const system = chain.at(-1);
  const { components: left, variants: leftValues } = componentChoices(chain);
  const outside = outsideComponents(chain, held);
  const byName = new Map(catalog.components.map((component) => [component.name, component]));
  const title = (name) => byName.get(name)?.title ?? name;
  // The shipped systems the chain is made of, nearest the system first, each with what it ships: a component's entry
  // is that of the nearest one that ships it.
  const ids = new Set(shipped);
  const entries = chain
    .map((layer, at) => (ids.has(layer.id) ? { id: layer.id, ships: shipsIn(chain.slice(0, at + 1), catalog, held) } : null))
    .filter(Boolean)
    .reverse();
  const registeredBy = (name) => entries.find(({ ships }) => ships.has(name))?.id ?? null;

  const components = [];
  const omittedVariants = {};
  for (const component of [...catalog.components].sort((a, b) => a.name.localeCompare(b.name))) {
    if (left.has(component.name) || outside[component.name]) continue;
    const entry = { name: component.name, title: component.title, level: component.level, listing: component.listing, layer: component.layer };
    const imports = importOf(component, registeredBy(component.name));
    if (component.web) entry.web = component.web.tag ? { tag: component.web.tag, import: imports.web, module: component.web.module } : { class: component.web.class, import: component.web.stylesheet };
    if (component.react) entry.react = { name: component.react.name, import: imports.react };
    if (component.variant) {
      // A composed component's variant is its member's (`from`): what the system leaves out of the member's is gone here too.
      const out = new Set([...(leftValues.get(component.variant.source)?.keys() ?? []), ...(leftValues.get(component.name)?.keys() ?? [])]);
      const values = [...new Set([...component.variant.values, ...addedValues(chain, component.variant.axis)])];
      entry.variants = values.filter((value) => !out.has(value));
      const gone = values.filter((value) => out.has(value));
      if (gone.length) omittedVariants[component.name] = gone;
    }
    components.push(entry);
  }

  const omitted = omittedOf(chain, held).map(({ name, ...entry }) => ({ name, title: title(name), ...entry }));

  return {
    system: system.id,
    name: system.name ?? system.id,
    ...(system.extends ? { extends: system.extends } : {}),
    chain: chain.map((layer) => layer.id),
    components,
    omitted,
    omittedVariants,
  };
}
