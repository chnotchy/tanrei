// Reads the generated token objects of androidx.compose.material3 (Apache-2.0) for the five Material 3 button
// sizes, the five icon button sizes and the loading indicator into a flat JSON snapshot: part of the reference
// `m3-like` is measured against (tokens/fidelity/m3-like.fidelity.json).
//
//   node packages/tokens-build/scripts/snapshot-androidx-material3.mjs <dir with the *Tokens.kt files> > tokens/fidelity/reference/androidx-material3.json
import fs from 'node:fs';
import path from 'node:path';

const [dir] = process.argv.slice(2);
if (!dir) throw new Error('usage: snapshot-androidx-material3.mjs <dir>');
const SIZES = ['XSmall', 'Small', 'Medium', 'Large', 'XLarge'];
const OBJECTS = [...SIZES.map((size) => `Button${size}Tokens`), ...SIZES.map((size) => `${size}IconButtonTokens`), 'LoadingIndicatorTokens'];
const tokens = {};
const versions = new Set();
for (const object of OBJECTS) {
  const source = fs.readFileSync(path.join(dir, `${object}.kt`), 'utf8');
  const version = source.match(/\/\/ VERSION: (\S+)/)?.[1];
  if (version) versions.add(version);
  for (const [, name, value] of source.matchAll(/inline val (\w+):[^\n]*\n\s+get\(\) = ([^\n]+)/g)) {
    const dp = value.match(/^([\d.]+)\.dp$/);
    tokens[`androidx.${object}.${name}`] = dp ? `${Number(dp[1])}dp` : value.trim();
  }
}
process.stdout.write(`${JSON.stringify({
  $comment: 'GENERATED by packages/tokens-build/scripts/snapshot-androidx-material3.mjs from androidx.compose.material3 tokens (Copyright The Android Open Source Project, Apache-2.0). Values only; no source text. Do not edit.',
  reference: { name: 'androidx.compose.material3 tokens', source: 'https://github.com/androidx/androidx/tree/androidx-main/compose/material3/material3/src/commonMain/kotlin/androidx/compose/material3/tokens', version: [...versions].sort().join(', '), license: 'Apache-2.0', description: 'Material 3: the five button sizes and the five icon button sizes (XSmall … XLarge), and the loading indicator.' },
  tokens: Object.fromEntries(Object.entries(tokens).sort(([a], [b]) => (a < b ? -1 : 1))),
}, null, 2)}\n`);
