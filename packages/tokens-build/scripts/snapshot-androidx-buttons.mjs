// Reads the generated token objects of androidx.compose.material3 (Apache-2.0) for the five Material 3
// Expressive button sizes into a flat JSON snapshot: the reference `m3-expressive-like` is measured against.
//
//   node packages/tokens-build/scripts/snapshot-androidx-buttons.mjs <dir with Button*Tokens.kt> > tokens/fidelity/reference/androidx-material3-buttons.json
import fs from 'node:fs';
import path from 'node:path';

const [dir] = process.argv.slice(2);
if (!dir) throw new Error('usage: snapshot-androidx-buttons.mjs <dir>');
const OBJECTS = ['ButtonXSmallTokens', 'ButtonSmallTokens', 'ButtonMediumTokens', 'ButtonLargeTokens', 'ButtonXLargeTokens'];
const tokens = {};
let version;
for (const object of OBJECTS) {
  const source = fs.readFileSync(path.join(dir, `${object}.kt`), 'utf8');
  version ??= source.match(/\/\/ VERSION: (\S+)/)?.[1];
  for (const [, name, value] of source.matchAll(/inline val (\w+):[^\n]*\n\s+get\(\) = ([^\n]+)/g)) {
    const dp = value.match(/^([\d.]+)\.dp$/);
    tokens[`androidx.${object}.${name}`] = dp ? `${Number(dp[1])}dp` : value.trim();
  }
}
process.stdout.write(`${JSON.stringify({
  $comment: 'GENERATED by packages/tokens-build/scripts/snapshot-androidx-buttons.mjs from androidx.compose.material3 tokens (Copyright The Android Open Source Project, Apache-2.0). Values only; no source text. Do not edit.',
  reference: { name: 'androidx.compose.material3 button size tokens', source: 'https://github.com/androidx/androidx/tree/androidx-main/compose/material3/material3/src/commonMain/kotlin/androidx/compose/material3/tokens', version, license: 'Apache-2.0', description: 'Material 3 Expressive: the five button sizes (XSmall … XLarge).' },
  tokens: Object.fromEntries(Object.entries(tokens).sort(([a], [b]) => (a < b ? -1 : 1))),
}, null, 2)}\n`);
