// Resolves the generated Sass token modules of material-web (Apache-2.0) into a flat JSON snapshot, the
// reference the `m3-like` preset is measured against (tokens/fidelity/).
//
//   node packages/tokens-build/scripts/snapshot-material-web.mjs <dir with _md-*.scss> <version> > tokens/fidelity/reference/material-web.json
//
// The modules use a tiny, regular subset of Sass: one `@function values…` returning a map whose values are
// literals, `if($exclude-hardcoded-values, null, <literal>)`, or `map.get($deps, '<module>', '<key>')`.
import fs from 'node:fs';
import path from 'node:path';

const [dir, version] = process.argv.slice(2);
if (!dir || !version) throw new Error('usage: snapshot-material-web.mjs <dir> <version>');
const read = (module) => fs.readFileSync(path.join(dir, `_${module}.scss`), 'utf8').replace(/\/\*\*[\s\S]*?\*\//g, '');

/** The top-level entries of the map a function returns: `'key': <expression>,` — expressions may nest parentheses. */
function entries(source, fn) {
  const start = source.indexOf(`@function ${fn}(`);
  if (start < 0) throw new Error(`no @function ${fn}`);
  let i = source.indexOf('@return (', start) + '@return ('.length;
  const out = [];
  let depth = 0, current = '';
  for (; i < source.length; i += 1) {
    const ch = source[i];
    if (ch === '(') depth += 1;
    if (ch === ')') { if (depth === 0) break; depth -= 1; }
    if (ch === ',' && depth === 0) { out.push(current); current = ''; } else current += ch;
  }
  if (current.trim()) out.push(current);
  return out.map((entry) => { const m = entry.match(/^\s*'([^']+)'\s*:\s*([\s\S]+)$/); return m && [m[1], m[2].replace(/\s+/g, ' ').trim()]; }).filter(Boolean);
}

function evaluate(expression, deps) {
  const hard = expression.match(/^if\(\s*\$exclude-hardcoded-values,\s*null,\s*([\s\S]+)\)$/);
  if (hard) return evaluate(hard[1].trim(), deps);
  const get = expression.match(/^map\.get\(\s*\$deps,\s*'([^']+)',\s*'([^']+)'\s*\)$/);
  if (get) return deps[get[1]]?.[get[2]];
  if (/map\.get/.test(expression)) return undefined; // composite shorthands (e.g. `label-text-type`): the discrete tokens are compared instead
  return expression.replace(/^\((.*)\)$/, '$1');
}

const valuesOf = (module, fn, deps = {}) => Object.fromEntries(entries(read(module), fn).map(([key, expression]) => [key, evaluate(expression, deps)]).filter(([, v]) => v !== undefined));

const palette = valuesOf('md-ref-palette', 'values');
const typeface = valuesOf('md-ref-typeface', 'values');
const sys = {
  'md-sys-elevation': valuesOf('md-sys-elevation', 'values'),
  'md-sys-shape': valuesOf('md-sys-shape', 'values'),
  'md-sys-state': valuesOf('md-sys-state', 'values'),
  'md-sys-typescale': valuesOf('md-sys-typescale', 'values', { 'md-ref-typeface': typeface }),
};
const color = { light: valuesOf('md-sys-color', 'values-light', { 'md-ref-palette': palette }), dark: valuesOf('md-sys-color', 'values-dark', { 'md-ref-palette': palette }) };

const tokens = {};
const put = (id, scheme, value) => { if (scheme) (tokens[id] ??= {})[scheme] = value; else tokens[id] = value; };
for (const [module, values] of Object.entries(sys)) for (const [key, value] of Object.entries(values)) put(`${module.replaceAll('-', '.').replace('md.sys', 'md.sys')}.${key}`, null, value);
for (const scheme of ['light', 'dark']) for (const [key, value] of Object.entries(color[scheme])) put(`md.sys.color.${key}`, scheme, value);
// The baseline tonal ramps: a preset reproduces them with `tones` on its palettes.
for (const [key, value] of Object.entries(palette)) put(`md.ref.palette.${key}`, null, value);
for (const [key, value] of Object.entries(typeface)) put(`md.ref.typeface.${key}`, null, value);

const components = fs.readdirSync(dir).filter((f) => /^_md-comp-.*\.scss$/.test(f)).map((f) => f.slice(1, -5)).sort();
for (const module of components) {
  const resolved = Object.fromEntries(['light', 'dark'].map((scheme) => [scheme, valuesOf(module, 'values', { ...sys, 'md-sys-color': color[scheme] })]));
  for (const key of Object.keys(resolved.light)) {
    const id = `md.comp.${module.slice('md-comp-'.length)}.${key}`;
    if (resolved.light[key] === resolved.dark[key]) put(id, null, resolved.light[key]);
    else for (const scheme of ['light', 'dark']) put(id, scheme, resolved[scheme][key]);
  }
}

process.stdout.write(`${JSON.stringify({
  $comment: 'GENERATED by packages/tokens-build/scripts/snapshot-material-web.mjs from material-web (Copyright Google LLC, Apache-2.0). Resolved token values only; no source text. Do not edit.',
  reference: { name: 'material-web', source: 'https://github.com/material-components/material-web/tree/main/tokens/versions', version, license: 'Apache-2.0', description: 'Google Material 3, audience 3P, platform Web, dynamic scheme with the baseline palette.' },
  components: components.map((m) => m.slice('md-comp-'.length)),
  tokens: Object.fromEntries(Object.entries(tokens).sort(([a], [b]) => (a < b ? -1 : 1))),
}, null, 2)}\n`);
