export type Strings = typeof en;
/** The dictionaries by primary language subtag (`zh-CN` → `zh`). A language without one reads English. */
const dictionaries: Record<string, Strings> = { en, ja, zh, es, hi, ar };
export const strings = (lang: string | undefined): Strings => dictionaries[(lang ?? 'en').toLowerCase().split('-')[0]] ?? en;

const ESCAPES: Record<string, string> = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' };
/** Fills `{name}` places in a string of the dictionary that is HTML; the values are text and are escaped. */
export const fill = (template: string, values: Record<string, string>) =>
  template.replace(/\{(\w+)\}/g, (place, name: string) => (name in values ? values[name].replace(/[&<>"]/g, (c) => ESCAPES[c]) : place));

/** Language of the content being rendered (differs from the URL locale on fallback pages). */
export function contentLang(Astro: { locals: any; currentLocale?: string }): string {
  return Astro.locals?.starlightRoute?.entryMeta?.lang ?? Astro.currentLocale ?? 'en';
}
/** URL prefix of the page being rendered (`` or `/ja`, `/zh-cn`, `/hi`, `/es`, `/ar`). */
export function localeBase(Astro: { locals: any }): string {
  const locale = Astro.locals?.starlightRoute?.locale;
  return locale ? `/${locale}` : '';
}
